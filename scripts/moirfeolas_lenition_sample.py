"""Draw a readable sample of the lenition export, for checking by eye.

``lenition_candidates.csv`` has 6,803 rows, which is too many to read on a
call. This takes a seeded sample stratified by lenited consonant, so all
nine consonants that can take a séimhiú are represented in proportion
rather than the sample being dominated by c.

It also lists separately the rows where the stem is attested in neither
source and is short, which is where a wrong demutation is most likely and
least obvious: a three-letter stem can look plausible without being a word.
"""
import argparse
import csv
import random
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = Path.home() / "data" / "tok" / "results" / "irish" / "corrected"
SOURCE = RESULTS / "lenition_candidates.csv"
DEST = ROOT / "docs" / "lenition_sample.md"

SEED = 20261113
SAMPLE_SIZE = 60
SHORT_STEM = 4


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", default=str(SOURCE))
    ap.add_argument("--out", default=str(DEST))
    ap.add_argument("--size", type=int, default=SAMPLE_SIZE)
    args = ap.parse_args()

    with open(args.source, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    by_cons = defaultdict(list)
    for r in rows:
        by_cons[r["lenited"].lower()].append(r)
    for c in by_cons:
        by_cons[c].sort(key=lambda r: r["word"])

    # Largest-remainder allocation, so the quotas sum to exactly --size and
    # no consonant present in the data is rounded away to nothing.
    total = len(rows)
    exact = {c: len(v) / total * args.size for c, v in by_cons.items()}
    quota = {c: max(1, int(exact[c])) for c in by_cons}
    while sum(quota.values()) > args.size:
        c = max(quota, key=lambda k: (quota[k] - exact[k], k))
        if quota[c] > 1:
            quota[c] -= 1
        else:
            break
    while sum(quota.values()) < args.size:
        c = max(quota, key=lambda k: (exact[k] - quota[k], k))
        quota[c] += 1

    rng = random.Random(SEED)
    sample = []
    for c in sorted(by_cons):
        pool = by_cons[c]
        n = min(quota[c], len(pool))
        sample.extend(rng.sample(pool, n) if n < len(pool) else list(pool))
    sample.sort(key=lambda r: (r["lenited"].lower(), r["word"]))

    unattested = sorted(
        (r for r in rows
         if r["base_in_corpus"] == "0" and r["base_in_moirfeolas"] == "0"
         and len(r["base"]) < SHORT_STEM),
        key=lambda r: (len(r["base"]), r["word"]))

    L = []
    a = L.append
    a("# Lenition candidates, a sample to check by eye")
    a("")
    a(f"{len(rows):,} rows in "
      f"`~/data/tok/results/irish/corrected/lenition_candidates.csv`. "
      f"This is {len(sample)} of them, stratified by lenited consonant and "
      f"drawn with `random.Random({SEED})`, so it is the same sample every "
      "time.")
    a("")
    a("Generated by `scripts/moirfeolas_lenition_sample.py`.")
    a("")
    a("`corpus` means the stem occurs on its own in `data/GA`; `table` means "
      "it is itself a MoirfEolas row. Either one is independent evidence "
      "that the demutation produced a real word.")
    a("")
    a("| word | stem | consonant | corpus | table |")
    a("|------|------|:---------:|:------:|:-----:|")
    for r in sample:
        a(f"| {r['word']} | {r['base']} | {r['lenited']} | "
          f"{'yes' if r['base_in_corpus'] == '1' else 'no'} | "
          f"{'yes' if r['base_in_moirfeolas'] == '1' else 'no'} |")
    a("")

    a("## Sample composition")
    a("")
    a("| consonant | in the export | in the sample |")
    a("|-----------|--------------:|--------------:|")
    in_sample = defaultdict(int)
    for r in sample:
        in_sample[r["lenited"].lower()] += 1
    for c in sorted(by_cons, key=lambda k: -len(by_cons[k])):
        a(f"| {c} | {len(by_cons[c]):,} | {in_sample[c]} |")
    a(f"| **total** | **{len(rows):,}** | **{len(sample)}** |")
    a("")

    a("## Stems attested nowhere, and short")
    a("")
    a(f"Rows where the stem occurs neither in `data/GA` nor as a MoirfEolas "
      f"row, and is shorter than {SHORT_STEM} characters. This is where a "
      "wrong demutation is both most likely and hardest to spot, because a "
      "short stem can look like a word without being one.")
    a("")
    if not unattested:
        a("None.")
    else:
        a(f"{len(unattested)} of {len(rows):,} rows.")
        a("")
        a("| word | stem | consonant |")
        a("|------|------|:---------:|")
        for r in unattested:
            a(f"| {r['word']} | {r['base']} | {r['lenited']} |")
        a("")
        a("`bhur` is the clearest false positive in the whole export: it is "
          "the possessive pronoun, not a lenited `bur`. It is the kind of "
          "thing a purely formal analyser cannot see, and the reason a "
          "lenition column wants a pass by eye over the short unattested "
          "stems before it is trusted.")
    a("")

    n_unatt_all = sum(1 for r in rows if r["base_in_corpus"] == "0"
                      and r["base_in_moirfeolas"] == "0")
    a(f"For context, {n_unatt_all:,} rows of {len(rows):,} "
      f"({n_unatt_all / len(rows) * 100:.1f}%) have a stem attested in "
      "neither source at any length. Most of those are long inflected forms "
      "whose lemma is in the corpus but whose exact form is not, so the "
      "flag is weak evidence on its own; combined with a short stem it is "
      "much stronger.")
    a("")

    dest = Path(args.out)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(L) + "\n")
    print(f"wrote {dest}: {len(sample)} sampled, {len(unattested)} "
          f"short-and-unattested, {n_unatt_all} unattested overall")


if __name__ == "__main__":
    main()
