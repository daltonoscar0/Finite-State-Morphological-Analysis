"""Generate docs/CALL_2026-11-13.md, a one-page sheet for the Jane Adkins call.

Everything is read from the result JSON in
~/data/tok/results/irish/corrected/, so the sheet cannot drift from the
numbers that were actually scored. Nothing here is typed by hand.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = Path.home() / "data" / "tok" / "results" / "irish" / "corrected"
DEST = ROOT / "docs" / "CALL_2026-11-13.md"

COMMIT = "0f31695c5315ce213cf4d5986a9c9c002ed740ef"

CATEGORIES = ["uru_only", "prefix_only", "suffix_only",
              "uru+prefix", "uru+suffix", "prefix+suffix", "all_affixes"]

# Her three published rows, 28 October, quoted for side-by-side reading only.
REFERENCE = {
    "Unigram 8k": [43.32, 50.00, 66.12, 40.70, 43.03, 50.83, 46.81, 35.98],
    "Morfessor":  [37.29, 72.22, 60.93, 33.92, 26.90, 45.70, 43.37, 27.12],
    "gaBERT":     [17.88, 50.00, 29.21, 17.27,  8.57, 14.61, 22.06,  9.61],
}


def vals(result):
    return [result["overall"]] + [result["categories"][c] for c in CATEGORIES]


def rowmd(label, values, bold=False):
    """One markdown row. ``bold`` emphasises the overall column only, since
    bolding all eight makes the table unreadable at a glance."""
    cells = []
    for i, v in enumerate(values):
        if v is None:
            cells.append("n/a")
        elif bold and i == 0:
            cells.append(f"**{v:.2f}**")
        else:
            cells.append(f"{v:.2f}")
    return f"| {label} | " + " | ".join(cells) + " |"


_SECTION = [0]


def sec(title):
    """Numbered heading. Counted rather than written out, so a section that
    is skipped (no round-trip JSON yet) does not leave a gap."""
    _SECTION[0] += 1
    return f"## {_SECTION[0]}. {title}"


HEAD8 = ("| | overall | uru_only | prefix_only | suffix_only | uru+prefix | "
         "uru+suffix | prefix+suffix | all_affixes |")
SEP8 = "|---|---:|---:|---:|---:|---:|---:|---:|---:|"


def main():
    her = json.loads((RESULTS / "her_protocol.json").read_text())
    allw = json.loads((RESULTS / "all_words.json").read_text())
    dprime = json.loads((RESULTS / "dprime_her_protocol.json").read_text())
    gabert = json.loads((RESULTS / "gabert.json").read_text())
    err = json.loads((RESULTS / "error_analysis.json").read_text())
    rt = {}
    rt_path = RESULTS / "roundtrip.json"
    if rt_path.exists():
        rt = json.loads(rt_path.read_text())

    L = []
    a = L.append

    a("# Call sheet, Jane Adkins, Friday 13 November 2026, 8:00 am ET")
    a("")
    a(f"MoirfEolas.csv at tknzn4Irish `{COMMIT[:7]}`. Her protocol throughout "
      "unless a row says otherwise, which means `--exclude-single-token`, "
      "because that is what reproduces her Unigram row.")
    a("")
    a("Generated by `scripts/moirfeolas_callsheet.py` from the result JSON.")
    a("")

    # --- 1. The protocol question -----------------------------------------
    a(sec("Ask this first"))
    a("")
    a("Her three published rows do not reproduce under one protocol.")
    a("")
    a("| row | reproduces at | only with |")
    a("|-----|--------------:|-----------|")
    a(f"| Unigram 8k | {her['backoff_UnigramLM_8k']['overall']:.2f} | "
      "`--exclude-single-token`, cased |")
    a(f"| gaBERT | {gabert['lower_all']['overall']:.2f} | all words plus "
      "`--do-lower-case` |")
    a("| Morfessor | not reproducible | no model ships in the repo |")
    a("")
    a("Both reproduce exactly on all eight columns, so this is not rounding. "
      "gaBERT under the other three combinations: "
      f"`--exclude-single-token` with lowercasing {gabert['lower_excl']['overall']:.2f}, "
      f"cased all-words {gabert['cased_all']['overall']:.2f}, "
      f"cased with the flag {gabert['cased_excl']['overall']:.2f}.")
    a("")

    # --- 2. The headline table --------------------------------------------
    a(sec("The three rows"))
    a("")
    a(HEAD8)
    a(SEP8)
    a(rowmd("Unigram 8k alone", vals(her["backoff_UnigramLM_8k"])))
    a(rowmd("Unigram 8k + Scalpel", vals(her["hybrid_UnigramLM_8k"]), bold=True))
    a(rowmd("SP-ULM 8k + Scalpel", vals(her["hybrid_SentencePieceULM_8k"]), bold=True))
    a("")
    a("Her reference rows, for comparison, as she sent them:")
    a("")
    a(HEAD8)
    a(SEP8)
    a(rowmd("Unigram 8k (hers)", REFERENCE["Unigram 8k"]))
    a(rowmd("Morfessor (hers)", REFERENCE["Morfessor"]))
    a(rowmd("gaBERT (hers)", REFERENCE["gaBERT"]))
    a("")
    a("**If asked what the system does:** it splits eclipsis and the h- and "
      "t-prefixes only. It identifies lenition but does not split it. It has "
      "no suffix analysis at all, so the suffix column is the back-off's own "
      "number. The headline is a mutation result wearing an aggregate's "
      "clothing.")
    a("")

    # --- 3. Ablation -------------------------------------------------------
    a(sec("Ablation, all words, one shared set of 35,517"))
    a("")
    a("The filter has to come off here: under `--exclude-single-token` the "
      "FST-alone row is scored on only the words it splits, and the "
      "no-segmentation row on nothing at all.")
    a("")
    a(HEAD8)
    a(SEP8)
    a(rowmd("no segmentation", vals(allw["identity"])))
    a(rowmd("mutation FST alone", vals(allw["fst_only"])))
    a(rowmd("subword alone (Unigram 8k)", vals(allw["backoff_UnigramLM_8k"])))
    a(rowmd("FST + subword (Unigram 8k)", vals(allw["hybrid_UnigramLM_8k"])))
    a(rowmd("subword alone (SP-ULM 8k)", vals(allw["backoff_SentencePieceULM_8k"])))
    a(rowmd("FST + subword (SP-ULM 8k)", vals(allw["hybrid_SentencePieceULM_8k"])))
    a("")
    a(f"The FST alone reaches {allw['fst_only']['overall']:.2f} because it "
      "scores zero on both affix columns and 96.9% of the data has a suffix. "
      "Neither layer carries the result.")
    a("")

    # --- 4. Absorption -----------------------------------------------------
    a(sec("Absorption, her `absorption.py`"))
    a("")
    a("| system | urú absorbed | urú mapping | suffix fully | suffix split | "
      "prefix fully | prefix split |")
    a("|--------|-------------:|------------:|-------------:|-------------:|"
      "-------------:|-------------:|")
    for label, key in [("Unigram 8k alone", "backoff_UnigramLM_8k"),
                       ("Unigram 8k + Scalpel", "hybrid_UnigramLM_8k"),
                       ("SP-ULM 8k alone", "backoff_SentencePieceULM_8k"),
                       ("SP-ULM 8k + Scalpel", "hybrid_SentencePieceULM_8k")]:
        ab = her[key]["absorption"]
        a(f"| {label} | {ab['uru_absorbed_%']:.2f} | {ab['uru_mapping_%']:.2f} | "
          f"{ab['suffix_fully_absorbed_%']:.2f} | {ab['suffix_split_absorbed_%']:.2f} | "
          f"{ab['prefix_fully_absorbed_%']:.2f} | {ab['prefix_split_absorbed_%']:.2f} |")
    a("")
    a("Urú absorption lands on the same figure for every back-off, because "
      "layer 1 does not depend on layer 2. Affix absorption barely moves, "
      "which is the same statement as the unchanged prefix and suffix columns.")
    a("")

    # --- 5. Category denominators -----------------------------------------
    a(sec("Category denominators, so nobody over-reads a column"))
    a("")
    counts = her["backoff_UnigramLM_8k"]["category_counts"]
    a("| category | words |")
    a("|----------|------:|")
    for name, n in sorted(counts.items(), key=lambda x: -x[1]):
        a(f"| {name} | {n:,} |")
    a("")
    uru_only = counts["uru_only"]
    base_u = her["backoff_UnigramLM_8k"]["categories"]["uru_only"]
    hyb_u = her["hybrid_UnigramLM_8k"]["categories"]["uru_only"]
    a(f"`uru_only` is {uru_only} words. Its {base_u:.2f} to {hyb_u:.2f} is "
      f"{base_u / 100 * uru_only:.1f} of {uru_only} going to "
      f"{hyb_u / 100 * uru_only:.1f} of {uru_only}. Her Morfessor row's 72.22 "
      f"in that column is {72.22 / 100 * uru_only:.1f} of {uru_only}. Nothing "
      "should be concluded from it. The gain actually lives in `uru+suffix` "
      f"({counts['uru+suffix']:,}) and `all_affixes` ({counts['all_affixes']:,}).")
    a("")

    # --- 6. d' -------------------------------------------------------------
    a(sec("The `d'` particle, measured not shipped"))
    a("")
    a(HEAD8)
    a(SEP8)
    a(rowmd("Unigram 8k + Scalpel", vals(her["hybrid_UnigramLM_8k"])))
    a(rowmd("Unigram 8k + Scalpel + d'", vals(dprime["hybrid_UnigramLM_8k"])))
    a(rowmd("SP-ULM 8k + Scalpel", vals(her["hybrid_SentencePieceULM_8k"])))
    a(rowmd("SP-ULM 8k + Scalpel + d'", vals(dprime["hybrid_SentencePieceULM_8k"])))
    a("")
    du = dprime["hybrid_UnigramLM_8k"]["overall"] - her["hybrid_UnigramLM_8k"]["overall"]
    ds = (dprime["hybrid_SentencePieceULM_8k"]["overall"]
          - her["hybrid_SentencePieceULM_8k"]["overall"])
    miss = err["uru_column"]["miss_causes"]
    dcount = next((v for k, v in miss.items() if k.startswith("d'")), 0)
    a(f"Worth {du:+.2f} and {ds:+.2f}, and it takes `uru_only` to "
      f"{dprime['hybrid_UnigramLM_8k']['categories']['uru_only']:.2f}. "
      f"{dcount} of the {err['uru_column']['no_split']} urú misses are `d'`. "
      "Left out because `d'` is a verbal particle, not an initial mutation. "
      "**Ask her:** the gold records it in the urú column, so does she "
      "consider that correct?")
    a("")

    # --- 7. Lenition cost --------------------------------------------------
    a(sec("Lenition: what splitting it costs today"))
    a("")
    a("Lenition is an infix, so no boundary split can isolate it. "
      "`hybrid_splinter` moves the marker out and leaves the stem contiguous, "
      "so its tokens no longer concatenate back to the surface.")
    a("")
    a("| family | 8k | 16k | 32k | 43k | 64k |")
    a("|--------|---:|----:|----:|----:|----:|")
    for fam in ("UnigramLM", "BPE"):
        cells = []
        for size in ("8k", "16k", "32k", "43k", "64k"):
            kh, ks = f"hybrid_{fam}_{size}", f"hybrid_splinter_{fam}_{size}"
            cells.append(f"{her[ks]['overall'] - her[kh]['overall']:+.2f}"
                         if kh in her else "")
        a(f"| {fam} | " + " | ".join(cells) + " |")
    a("")
    u8 = her["hybrid_UnigramLM_8k"]
    s8 = her["hybrid_splinter_UnigramLM_8k"]
    a(f"At Unigram 8k it is {u8['overall']:.2f} to {s8['overall']:.2f}. Every "
      "column is identical to two decimals except `suffix_only`, "
      f"{u8['categories']['suffix_only']:.2f} to "
      f"{s8['categories']['suffix_only']:.2f}. **That is the whole argument:** "
      "none of the lenited words carries a gold urú or a gold prefix, so the "
      "only column that can move is the suffix one. The split is right and "
      "the gold has nowhere to record it.")
    a("")

    # --- 8. Round trip -----------------------------------------------------
    if rt:
        a(sec("Round trip, since Splinter needs a lossless transform"))
        a("")
        a("| scheme | words | rebuilt exactly | failures |")
        a("|--------|------:|----------------:|---------:|")
        for scheme in ("concat", "splinter"):
            s = rt["schemes"][scheme]
            a(f"| {scheme} | {s['n']:,} | {s['ok']:,} | {s['fail']:,} |")
        a("")
        a("| scheme | tag | words | rebuilt exactly | failures |")
        a("|--------|-----|------:|----------------:|---------:|")
        for scheme in ("concat", "splinter"):
            for tag, c in sorted(rt["schemes"][scheme]["by_tag"].items()):
                a(f"| {scheme} | {tag} | {c['n']:,} | {c['ok']:,} | {c['fail']:,} |")
        a("")
        a(rt["verdict"])
        a("")

    # --- 9. Scorer issues --------------------------------------------------
    a(sec("Three things in her code, raised not patched"))
    a("")
    a("| issue | count |")
    a("|-------|------:|")
    a("| words with an empty first token, SP-ULM 8k baseline | "
      f"{her['backoff_SentencePieceULM_8k']['n_empty_token_words']:,} |")
    a("| the same, SP-ULM 8k hybrid | "
      f"{her['hybrid_SentencePieceULM_8k']['n_empty_token_words']:,} |")
    a("| the same, Unigram 8k, either system | "
      f"{her['backoff_UnigramLM_8k']['n_empty_token_words']:,} |")
    a("| eclipsed capitalised vowels the gold misses | "
      f"{len(err['uru_column']['false_positives']):,} |")
    a("| rows marking an urú on an ordinary t-initial word | "
      f"{miss.get('other', 0):,} |")
    a("")
    fp = err["uru_column"]["false_positives"][:6]
    a(f"`remove_specials` strips a leading `▁` unconditionally, so a "
      "standalone `▁` piece becomes an empty first token that then fails "
      "every position-anchored test. It affects her published SentencePiece "
      "rows exactly as much as it affects mine, which is why it is raised "
      "rather than patched, and why the Unigram comparison is the clean one.")
    a("")
    a(f"The missed capitals are all eclipsis of a capitalised vowel written "
      f"without a hyphen: {', '.join('`' + w + '`' for w in fp)}. "
      "`SPECIAL_PREFIXES` maps bare `n` to `d g D G` only. The spurious `t` "
      "rows are the mirror: `téad`, `tuartha`, `tiarratas`, `tiompar` read as "
      "`t` plus a vowel. Both look like one case condition.")
    a("")

    # --- 10. Agenda --------------------------------------------------------
    a(sec("Things to get answers on"))
    a("")
    a("1. Which protocol do the published numbers use?")
    a("2. Can the Morfessor model or its training script go in the repo?")
    a("3. Lenition column: what shape, and does the urú scoring rule carry "
      "over to it?")
    a("4. Is `d'` correctly in the urú column, or should it be its own thing?")
    a("5. The two patches, prepared and ready to send as `git format-patch` "
      "files in `patches/`.")
    a("6. Elaine's analyser: the scorer now takes any analyser's batch output "
      "as a TSV, so the comparison needs only her output, not her toolchain.")
    a("")

    DEST.write_text("\n".join(L) + "\n")
    print(f"wrote {DEST} ({len(L)} lines)")


if __name__ == "__main__":
    main()
